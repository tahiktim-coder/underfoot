export const WISP = (() => {
  const g = {};
  const lines = SRC.split('\n');
  let i = 0;
  while (i < lines.length) {
    const ch = lines[i];
    if (ch.length !== 1) { i++; continue; }
    i++;
    const rows = [];
    while (i < lines.length && lines[i].length > 1 && /^[.#]+$/.test(lines[i])) rows.push(lines[i++]);
    // single-column glyphs ('.', ':', '!', ''') have 1-char rows; collect those too
    while (i < lines.length && lines[i].length === 1 && /^[.#]$/.test(lines[i]) && rows.length < 9 && (rows.length === 0 || rows[0].length === 1)) rows.push(lines[i++]);
    g[ch] = { w: rows.reduce((m, r) => Math.max(m, r.length), 0), rows };
  }
  g[' '] = { w: 3, rows: [] };
  return g;
})();

export function measureWisp(text, scale = 1) {
  let w = 0;
  for (const c of text) { const gl = WISP[c] || WISP['?']; w += (gl.w + 1) * scale; }
  return Math.max(0, w - scale);
}

// plot(x, y) is called for every lit pixel (scaled). Returns the advance.
export function drawWisp(text, x, y, plot, scale = 1) {
  let cx = x;
  for (const c of text) {
    const gl = WISP[c] || WISP['?'];
    gl.rows.forEach((r, ry) => {
      for (let rx = 0; rx < r.length; rx++) if (r[rx] === '#') {
        for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) plot(cx + rx * scale + sx, y + ry * scale + sy);
      }
    });
    cx += (gl.w + 1) * scale;
  }
  return cx - x;
}
